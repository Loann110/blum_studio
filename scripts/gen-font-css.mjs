// Fontsource names: abril-fatface-latin-400-normal.woff2 -> { family, weight, style }.
function parseFontsource(stem) {
  const parts = stem.split("-");
  for (let i = parts.length; i > 0; i--) {
    const family = FAMILIES[parts.slice(0, i).join("-")];
    if (!family) continue;
    let weight = "400";
    let style = "normal";
    for (const bit of parts.slice(i)) {
      if (bit === "latin" || bit === "latin-ext" || bit === "ext") continue;
      if (bit === "normal" || bit === "italic") {
        style = bit;
        continue;
      }
      // Variable files glue style and axes in one bit (Italic[wght]): read both halves.
      if (bit.toLowerCase().includes("italic")) style = "italic";
      if (bit.includes("wght")) weight = "100 900";
      else if (/^\d+$/.test(bit)) weight = bit;
    }
    return { family, weight, style };
  }
  return null;
}

// Google Fonts names: anton-Anton-Regular.ttf, bricolagegrotesque-…[opsz,wdth,wght].ttf.
function parseGoogle(stem) {
  const family = FAMILIES[stem.split("-")[0].split("[")[0]];
  if (!family) return null;
  const lower = stem.toLowerCase();
  const style = lower.includes("italic") ? "italic" : "normal";
  const variable = ["variable", "[opsz", "[wght", "[wdth"].some((mark) => lower.includes(mark));
  const weight = variable ? "100 900" : lower.includes("bold") ? "700" : "400";
  return { family, weight, style };
}

const base = (process.argv[2] ?? "/assets/fonts").replace(/\/+$/, "");
const faces = new Map();
const unmatched = [];
for (const file of fs.readdirSync(fontsDir).sort()) {
  const ext = path.extname(file);
  if (ext !== ".woff2" && ext !== ".ttf") continue;
  const stem = path.basename(file, ext);
  const face = parseFontsource(stem) ?? parseGoogle(stem);
  if (!face) {
    unmatched.push(file);
    continue;
  }
  // One face per family, weight, style and format: prefer latin over latin-ext.
  const key = [face.family, face.weight, face.style, ext].join("\u0000");
  const rank = file.includes("latin-ext") ? 1 : 0;
  if (!faces.has(key) || rank < faces.get(key).rank) faces.set(key, { ...face, rank, file, ext });
}

const blocks = [...faces.keys()].sort().map((key) => {
  const { family, weight, style, file, ext } = faces.get(key);
  const format = ext === ".woff2" ? "woff2" : "truetype";
  return `@font-face {\n  font-family: "${family}";\n  font-style: ${style};\n  font-display: swap;\n` +
    `  font-weight: ${weight};\n  src: url("${base}/${file}") format("${format}");\n}`;
});
console.log(["/* Generated by scripts/gen-font-css.mjs: local OFL fonts. */", ...blocks].join("\n\n"));
if (unmatched.length) console.log(`/* unmatched: ${unmatched.join(", ")} */`);
