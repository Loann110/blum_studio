// Mean colour of each paper texture, for lint contrast on image backgrounds.
// Usage: node scripts/gen-texture-colours.mjs > ui/engine/lint/texture-colours.ts
// Needs the Playwright Chromium already used for export (ui/node_modules).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const texturesDir = path.join(root, "assets", "textures");
const require = createRequire(path.join(root, "ui", "package.json"));
const { chromium } = require("playwright-core");

const files = fs.readdirSync(texturesDir).filter((f) => f.endsWith(".jpg")).sort();

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const means = {};
  for (const file of files) {
    const data = fs.readFileSync(path.join(texturesDir, file)).toString("base64");
    // Draw down to 32x32: the smoothing averages the grain for us.
    const [r, g, b] = await page.evaluate(async (src) => {
      const img = new Image();
      img.src = `data:image/jpeg;base64,${src}`;
      await img.decode();
      const canvas = document.createElement("canvas");
      canvas.width = 32;
      canvas.height = 32;
      const ctx = canvas.getContext("2d");
      ctx.drawImage(img, 0, 0, 32, 32);
      const px = ctx.getImageData(0, 0, 32, 32).data;
      let rr = 0, gg = 0, bb = 0;
      for (let i = 0; i < px.length; i += 4) {
        rr += px[i];
        gg += px[i + 1];
        bb += px[i + 2];
      }
      const n = px.length / 4;
      return [rr / n, gg / n, bb / n];
    }, data);
    const hex = "#" + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
    means[`textures/${file}`] = hex;
  }
  await browser.close();
  const rows = Object.entries(means).map(([k, v]) => `  "${k}": "${v}",`).join("\n");
  console.log(
    `// Generated by scripts/gen-texture-colours.mjs: mean colour of each paper texture.\n` +
    `// Do not edit by hand; rerun the script when a texture changes.\n` +
    `export const TEXTURE_COLOURS: Record<string, string> = {\n${rows}\n};\n`,
  );
} catch (e) {
  await browser.close();
  throw e;
}
